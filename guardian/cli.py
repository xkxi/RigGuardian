def cmd_gpus(argv: list[str], a) -> int:
    from guardian.telemetry import NoGpuError, TelemetryStore, inventory_table, make_source

    p = argparse.ArgumentParser(prog="rig-guardian gpus")
    p.add_argument("--watch", type=float, metavar="SECONDS", help="refresh every SECONDS until Ctrl-C")
    p.add_argument("--fake-gpus", type=int, metavar="N")
    o = p.parse_args(argv)
    try:
        cfg = _load(a)
    except SystemExit:
        cfg = Config()
    _use_fake(cfg, o.fake_gpus)
    try:
        src = make_source(cfg)
    except NoGpuError as e:
        print(e)
        return 1
    inv = src.inventory()
    try:
        cfg.resolve_gpus([g["gpu"] for g in inv])
        print(inventory_table(inv, cfg))
    except ValueError as e:
        print(inventory_table(inv))
        print(f"config problem: {e}")
    store = TelemetryStore()
    while True:
        store.add(src.read())
        print()
        for g in store.gpus():
            s = store.latest(g)
            if s.get("lost"):
                print(f"  GPU {g} {store.label(g)}: LOST")
                continue
            def num(v, fmt="{:.0f}"):
                return fmt.format(v) if v is not None else "?"

            mem = f"{num(s.get('mem_used') and s['mem_used'] / 2**30, '{:.1f}')}/" \
                  f"{num(s.get('mem_total') and s['mem_total'] / 2**30, '{:.1f}')} GiB"
            if s.get("mem_used") == 0:
                mem = "0.0/" + mem.split("/", 1)[1]
            pw = f"{num(s.get('power_w'))}/{num(s.get('power_limit_w'))} W"
            procs = f"{len(s['procs'])} process(es)" if s.get("vendor", "nvidia") == "nvidia" else ""
            print(f"  GPU {g} {store.label(g):<12} {num(s.get('temp_c')):>4} °C  {mem:>14}  "
                  f"{num(s.get('util')):>3}% busy  {pw}  {procs}".rstrip())
        if not o.watch:
            return 0
        try:
            time.sleep(o.watch)
        except KeyboardInterrupt:
            return 0


def cmd_start(argv: list[str], a) -> int:
    from guardian.daemon import start

    p = argparse.ArgumentParser(prog="rig-guardian start")
    p.add_argument("--fake-gpus", type=int, metavar="N", help="simulate N GPUs (development only)")
    p.add_argument("--log-level", default="INFO")
    o = p.parse_args(argv)
    logging.basicConfig(level=o.log_level.upper(), format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)
    cfg = _load(a)
    _use_fake(cfg, o.fake_gpus)
    start(cfg)
    return 0



def cmd_service(argv: list[str], a) -> int:
    p = argparse.ArgumentParser(prog="rig-guardian service", description="systemd user services (Linux)")
    p.add_argument("action", choices=["install", "uninstall", "status"])
    p.add_argument("--enable", action="store_true", help="also enable and start now")
    p.add_argument("--llm-model", help="GGUF model for the optional language model (needs gpus.agent)")
    p.add_argument("--llama-server", default="llama-server", help="path to llama.cpp's llama-server")
    o = p.parse_args(argv)
    if not shutil.which("systemctl"):
        print("systemd is not available here (it is Linux-only). Run `rig-guardian start` in tmux or screen, "
              "or under your platform's service manager.")
        return 1
    units = Path("~/.config/systemd/user").expanduser()
    names = ["rig-guardian.service", "rig-llm.service"]

    def sc(*args: str) -> int:
        print("$ systemctl --user " + " ".join(args))
        return subprocess.run(["systemctl", "--user", *args]).returncode

    if o.action == "status":
        return sc("status", "--no-pager", *[n for n in names if (units / n).exists()])
    if o.action == "uninstall":
        for n in names:
            if (units / n).exists():
                sc("disable", "--now", n)
                (units / n).unlink()
        sc("daemon-reload")
        return 0
    cfg = _load(a)
    units.mkdir(parents=True, exist_ok=True)
    if o.llm_model:
        if cfg.gpus.agent is None:
            print("Set gpus.agent in config.yaml to the GPU that should run the model, then run this again.")
            return 1
        server = shutil.which(o.llama_server) or o.llama_server
        from guardian.telemetry import NoGpuError, make_source
        from guardian.vendors import pin_env

        try:  # pin the model server to the agent card the way that card's vendor expects
            card = next(g for g in make_source(cfg).inventory() if g["gpu"] == cfg.gpus.agent)
        except (NoGpuError, StopIteration):
            print(f"gpus.agent is {cfg.gpus.agent}, but no such GPU was found. Check `rig-guardian gpus`.")
            return 1
        env = "\n".join(f"Environment={_sd_quote(f'{k}={v}')}" for k, v in pin_env([card]).items()
                        if k != "PYTORCH_CUDA_ALLOC_CONF")
        from urllib.parse import urlsplit

        url = urlsplit(cfg.brain.url)
        if url.hostname not in ("127.0.0.1", "localhost", "::1"):
            print(f"brain.url is {cfg.brain.url}: this service only serves a model on this machine. "
                  f"Set brain.url to http://127.0.0.1:<port> or run the model server yourself.")
            return 1
        model = Path(o.llm_model).expanduser().resolve()
        if not model.is_file():
            print(f"Model file not found: {model}")
            return 1
        (units / "rig-llm.service").write_text(LLM_UNIT.format(
            gpu=cfg.gpus.agent, env=env, server=_sd_quote(server), model=_sd_quote(model),
            host="127.0.0.1", port=url.port or 8081))
        if not cfg.brain.enabled:
            print("Note: set brain.enabled: true in config.yaml to use the model for plain-English messages.")
    (units / "rig-guardian.service").write_text(GUARDIAN_UNIT.format(
        home=str(cfg.root).replace("%", "%%"), python=_sd_quote(sys.executable), config=_sd_quote(cfg.config_path),
        after_llm=" rig-llm.service" if o.llm_model else ""))
    print(f"Wrote {units / 'rig-guardian.service'}" + (" and rig-llm.service" if o.llm_model else ""))
    failed = sc("daemon-reload") != 0
    if o.enable:
        if o.llm_model:
            failed |= sc("enable", "--now", "rig-llm.service") != 0
        failed |= sc("enable", "--now", "rig-guardian.service") != 0
    else:
        print("Start it with: systemctl --user enable --now rig-guardian")
    if failed:
        print("systemctl reported an error (see above): the service files are written, but the service is "
              "not confirmed running. Check: systemctl --user status rig-guardian")
        return 1
    user = os.environ.get("USER", "$USER")
    print(f"Keep it running while logged out (once): sudo loginctl enable-linger {user}")
    return 0


# ---- job commands (same router as Telegram) ---------------------------------------------------
def agent_running(db, max_age_s: float = 30.0) -> bool:
    """True if a running agent has written its heartbeat to the database in the last seconds."""
    try:
        return time.time() - float(db.kv_get("agent_heartbeat") or 0) < max_age_s
    except ValueError:
        return False


def build_agent(cfg: Config):
    import json

    from guardian.actions import Agent
    from guardian.brain import Brain
    from guardian.db import Database
    from guardian.notifier import Notifier
    from guardian.reports import Reports
    from guardian.runner import Runner
    from guardian.telemetry import NoGpuError, TelemetryStore, make_source

    cfg.runs_dir.mkdir(parents=True, exist_ok=True)
    db = Database(cfg.db_path)
    store = TelemetryStore.from_db(db)  # the running agent's newest readings
    inventory = json.loads(db.kv_get("gpu_inventory") or "null")
    rows = sorted(({"gpu": int(i), **(v if isinstance(v, dict) else {})} for i, v in inventory.items()),
                  key=lambda r: r["gpu"]) if inventory else []
    if not store.gpus() or not rows:  # agent not running yet: read the GPUs directly
        try:
            src = make_source(cfg)
            store.add(src.read())
            rows = src.inventory()
        except NoGpuError:
            pass
    try:
        cfg.resolve_gpus(rows)
    except ValueError as e:
        print(f"warning: {e}", file=sys.stderr)
        if not cfg.gpus.resolved:
            cfg.gpus.training = []
    notifier = Notifier(db, cfg.telegram)
    brain = Brain(cfg.brain) if cfg.brain.enabled else None
    box: list = []
    reports = Reports(cfg, db, store, lambda: box[0].templates(), brain=brain)
    runner = Runner(cfg, db, store, notifier, reports)
    box.append(runner)
    return Agent(cfg, db, runner, reports, notifier, brain=brain)


def cmd_job(words: list[str], a) -> int:
    agent = build_agent(_load(a))
    if words[0] == "ask":
        text = " ".join(words[1:])
    else:  # quoted so the router's shell-style split gives back exactly these words
        text = "/" + " ".join(shlex.quote(w) for w in words).lstrip("/")
    code = 0
    for name, why in getattr(agent.runner, "template_problems", []) or []:
        print(f"warning: template file {name} is being ignored: {why}", file=sys.stderr)
    if not agent_running(agent.db):
        print("note: the agent is not running (`rig-guardian start`); readings may be old and queued jobs "
              "wait until it starts.", file=sys.stderr)
    for r in agent.handle_text(None, text, trusted=True) or []:
        print(r.text)
        if r.photo:
            print(f"(image: {r.photo})")
        if r.document:
            print(r.document[1].decode(errors="replace"))
        if r.buttons:
            ok = a.yes or _ask("Confirm? [y/N] ").lower() in ("y", "yes")
            res = agent.handle_callback(None, r.buttons[0 if ok else 1][1], trusted=True)
            if res:
                print(res.text)
                code = 1 if res.text.startswith("🚫") else 0
        elif r.text.startswith(("🚫", "The AI is turned off", "AI offline", "The AI's answer")):
            code = 1
    return code


def main(argv: list[str] | None = None) -> None:
    argv = list(sys.argv[1:] if argv is None else argv)
    ap = argparse.ArgumentParser(prog="rig-guardian", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter, add_help=False)
    ap.add_argument("--home")
    ap.add_argument("--config")
    ap.add_argument("-y", "--yes", action="store_true")
    ap.add_argument("-h", "--help", action="store_true")
    a, rest = ap.parse_known_args(argv)
    # options may also come after the command: `rig-guardian run toy-mlp -y`
    if "-y" in rest or "--yes" in rest:
        a.yes = True
        rest = [w for w in rest if w not in ("-y", "--yes")]
    if not rest or (a.help and not rest):
        print(__doc__)
        sys.exit(0)
    cmd, args = rest[0], rest[1:]
    handlers = {"init": cmd_init, "doctor": cmd_doctor, "gpus": cmd_gpus, "start": cmd_start, "service": cmd_service}
    if a.help:
        if cmd in handlers:
            sys.exit(handlers[cmd](["--help"], a))
        print(__doc__)  # asking for help never runs a job command
        sys.exit(0)
    if cmd in handlers:
        sys.exit(handlers[cmd](args, a))
    sys.exit(cmd_job(rest, a))


if __name__ == "__main__":
    main()

"""rig-guardian: one command for setup, running and day-to-day control.

Setup and running
  rig-guardian init                 detect GPUs, write <home>/config.yaml (home: ~/rig-guardian)
  rig-guardian doctor               check driver, GPUs, templates and PyTorch builds
  rig-guardian gpus [--watch S]     every GPU with live readings (works without the agent)
  rig-guardian start                run the agent in the foreground
  rig-guardian service install      run it as a systemd user service (Linux)

Controlling jobs (the same commands as Telegram; changes ask y/N, or pass -y)
  rig-guardian status | jobs | job <id> | templates | logs <id> | plot <id>
  rig-guardian run <template> key=value ...      rig-guardian rerun <id> key=value ...
  rig-guardian pause|resume|stop|cancel|ckpt <id>
  rig-guardian hold | unhold | clear <gpu> | digest
  rig-guardian ask "rerun the last one with half the learning rate"

Global options: --home DIR (or $RIG_GUARDIAN_HOME), --config FILE, -y/--yes
"""


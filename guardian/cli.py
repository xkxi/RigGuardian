def cmd_init(argv: list[str], a) -> int:
    from guardian.examples import TOY_SCRIPT, toy_template
    from guardian.telemetry import FakeSource, NoGpuError, inventory_table, make_source

    p = argparse.ArgumentParser(prog="rig-guardian init", description="Detect GPUs and write a config.")
    p.add_argument("--fake-gpus", type=_positive_int, metavar="N", help="simulate N GPUs (no GPU hardware needed)")
    p.add_argument("--agent-gpu", type=int, help="GPU index for the optional language model (never trains)")
    p.add_argument("--exclude", type=_index_list, default=[],
                   help="comma-separated GPU indexes to monitor but never train on")
    p.add_argument("--telegram-token", help="bot token (prefer the prompt: a token on the command line ends up "
                                            "in your shell history)")
    p.add_argument("--telegram-user", type=int, action="append", default=[])
    p.add_argument("--force", action="store_true",
                   help="replace an existing config.yaml (the old one is kept as config.yaml.bak)")
    o = p.parse_args(argv)

    home = _home(a)
    cfg_path = _config_file(a)
    old_users: list[int] = []
    if cfg_path.exists():
        if not o.force:
            print(f"{cfg_path} already exists (use --force to replace it; the old one is kept as a .bak file).")
            return 1
        try:
            old_users = list(load_config(cfg_path).telegram.allowed_user_ids)
        except Exception as e:  # not one of ours: refuse rather than destroy somebody's file
            print(f"{cfg_path} exists and is not a Rig Guardian config ({type(e).__name__}); not touching it. "
                  f"Choose another folder with --home.")
            return 1
    try:
        src = FakeSource([FakeGpu()] * o.fake_gpus) if o.fake_gpus else make_source(Config())
    except NoGpuError as e:
        print(f"No GPUs found: {e}")
        return 1
    inv = src.inventory()
    indexes = [g["gpu"] for g in inv]
    exclude = list(o.exclude)
    bad = [i for i in exclude + ([o.agent_gpu] if o.agent_gpu is not None else []) if i not in indexes]
    if bad:
        print(f"GPU index {bad} does not exist; detected: {indexes}")
        return 1
    print(f"Found {len(inv)} GPU{'s' if len(inv) != 1 else ''}:\n{inventory_table(inv)}")
    roles = Config()
    roles.gpus.agent, roles.gpus.exclude = o.agent_gpu, exclude
    training = roles.resolve_gpus(inv).gpus.training
    print(f"Training on: {', '.join(f'GPU {i}' for i in training) or 'none'}")
    for g in inv:
        if g["gpu"] not in training and g["gpu"] != o.agent_gpu and g["gpu"] not in exclude:
            why = "integrated graphics" if g.get("integrated") else (g.get("note") or "not usable for training")
            print(f"  GPU {g['gpu']} is monitored only: {why}. To train on it anyway, list the indexes under "
                  f"gpus.training in config.yaml.")
    vendors = sorted({g.get("vendor") or "nvidia" for g in inv if g["gpu"] in training})
    if len(vendors) > 1:
        print("  Cards from several vendors will train: give each template a `vendor:` line (see the README).")

    token, users = o.telegram_token, list(o.telegram_user) or old_users
    if sys.stdin.isatty() and not a.yes:
        if not token:
            token = _ask("Telegram bot token (from @BotFather; Enter to skip, you can add it later): ") or None
        if token and not users:
            uid = _ask("Your numeric Telegram user ID (Enter to skip): ")
            users = [int(uid)] if uid.isascii() and uid.isdigit() else []

    home.mkdir(parents=True, exist_ok=True)
    try:  # run logs, the database and .env live here: keep other accounts out
        home.chmod(0o700)
    except OSError:
        pass
    (home / "templates").mkdir(exist_ok=True)
    (home / "runs").mkdir(exist_ok=True)
    if cfg_path.exists():
        shutil.copyfile(cfg_path, cfg_path.with_name(cfg_path.name + ".bak"))
    fake = ""
    if o.fake_gpus:
        fake = "\n  fake_gpus: " + yaml.safe_dump([FakeGpu().model_dump()] * o.fake_gpus,
                                                 default_flow_style=True, width=200).strip()
    cfg_path.write_text(CONFIG_TEMPLATE.format(
        date=time.strftime("%Y-%m-%d"),
        inventory="\n".join("#" + ln for ln in inventory_table(inv).splitlines()),
        training="auto", agent=o.agent_gpu if o.agent_gpu is not None else "null",
        exclude=exclude, source="fake" if o.fake_gpus else "auto", fake=fake,
        users=users, brain="true" if o.agent_gpu is not None else "false"))
    load_config(cfg_path)  # fail now, not at start, if anything above is malformed

    env = home / ".env"
    if not env.exists() or token:
        # keep whatever else is in the file; only the token line is ours to replace
        kept = [ln for ln in (env.read_text().splitlines() if env.exists() else [])
                if not ln.strip().removeprefix("export ").lstrip().startswith(("TELEGRAM_TOKEN=", "# TELEGRAM_TOKEN="))]
        line = f"TELEGRAM_TOKEN={token}" if token else "# TELEGRAM_TOKEN=123456:your-bot-token"
        fd = os.open(env, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)  # never world-readable, even briefly
        with os.fdopen(fd, "w") as f:
            f.write("\n".join([line, *kept]) + "\n")
    env.chmod(0o600)
    toy = home / "templates" / "toy-mlp.yaml"
    if not toy.exists():
        toy.write_text("# Tiny model for testing the agent end to end (runs on CPU too).\n"
                       + yaml.safe_dump(toy_template(sys.executable), sort_keys=False))
    example = home / "templates" / "my-project.yaml.example"
    shutil.copyfile(TOY_SCRIPT.parent / "cifar-resnet.yaml", example)

    try:
        import torch  # noqa: F401

        has_torch = True
    except ImportError:
        has_torch = False
    print(f"\nWrote {cfg_path}, {env} and {home / 'templates'}/.")
    if not has_torch:
        print("Note: PyTorch is not installed in this Python, so the toy-mlp example cannot run here "
              "(pip install torch). Your own templates use their own Python.")
    hint = f" --home {home}" if home != default_config_path().expanduser().resolve().parent else ""
    print(f"""
Next steps:
  rig-guardian{hint} doctor                    check drivers, GPUs and PyTorch builds
  rig-guardian{hint} start                     run the agent (Ctrl-C to stop; jobs keep running)
  rig-guardian{hint} run toy-mlp epochs=2 -y   in another terminal: a 30-second test job
  rig-guardian{hint} service install --enable  run it in the background at boot (Linux)
Add your own runs by copying {example.name} in {home / 'templates'}.""")
    return 0



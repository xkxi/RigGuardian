# ---- helpers ------------------------------------------------------------------------------
def _home(a) -> Path:
    if a.config:
        return Path(a.config).expanduser().resolve().parent
    if a.home:
        return Path(a.home).expanduser().resolve()
    return default_config_path().expanduser().resolve().parent


def _config_file(a) -> Path:
    return Path(a.config).expanduser().resolve() if a.config else _home(a) / "config.yaml"


def _load(a) -> Config:
    path = _config_file(a)
    if not path.exists():
        sys.exit(f"No config at {path}. Run `rig-guardian init` first (or pass --home/--config).")
    try:
        cfg = load_config(path)
    except (ValueError, yaml.YAMLError) as e:  # pydantic's ValidationError is a ValueError
        sys.exit(f"{path} is not a valid Rig Guardian config:\n{e}")
    load_env(cfg.root / ".env")
    return cfg


def _positive_int(text: str) -> int:
    try:
        n = int(text)
    except ValueError:
        raise argparse.ArgumentTypeError(f"{text!r} is not a whole number") from None
    if n < 1:
        raise argparse.ArgumentTypeError("must be 1 or more")
    return n


def _index_list(text: str) -> list[int]:
    try:
        out = [int(x) for x in text.split(",") if x.strip()]
    except ValueError:
        raise argparse.ArgumentTypeError(f"{text!r} is not a comma-separated list of GPU indexes") from None
    if any(i < 0 for i in out):
        raise argparse.ArgumentTypeError("GPU indexes cannot be negative")
    return out


def _sd_quote(value: object) -> str:
    """One argument for a systemd unit line: quoted, with systemd's own escapes (% and $)."""
    s = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    return f'"{s}"'


def _use_fake(cfg: Config, n: int | None) -> None:
    if n:
        cfg.telemetry.source = "fake"
        cfg.telemetry.fake_gpus = [FakeGpu() for _ in range(n)]


def _ask(prompt: str) -> str:
    try:
        return input(prompt).strip()
    except EOFError:
        return ""


